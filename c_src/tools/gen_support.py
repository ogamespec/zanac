#!/usr/bin/env python3
"""Generate the machine-written support files of the port.

  c_src/zanac/thunks.c   one C function per original three-byte `JMP <target>`
                         shim (the bank-API trampolines), as a tail call.
  c_src/zanac/stubs.c    placeholders for every procedure that is still
                         missing: the tool scans the ported sources for
                         `void <name>(void)` definitions and emits a stub for
                         each of the remaining procedures.  The stubs are not
                         weak (so the file works with any compiler), they are
                         simply removed as soon as the real definition exists.

Run it before every build (the build scripts do).

Generated from src/bankN.asm, Build/bankN.lst and c_src/analysis/procedures.json.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "c_src", "zanac")
ANALYSIS = os.path.join(ROOT, "c_src", "analysis")

DEFINITION = re.compile(r"^void\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*void\s*\)", re.MULTILINE)
SCAN_SKIP = {"stubs.c", "thunks.c"}


def read_lines(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read().splitlines()


def thunk_target(lines, proc):
    for idx in range(proc["start"], min(proc["start"] + 6, len(lines) + 1)):
        text = lines[idx - 1].split(";")[0].strip()
        text = re.sub(r"^[A-Za-z_][A-Za-z0-9_]*:\s*", "", text)
        m = re.match(r"^JMP\s+([A-Za-z_][A-Za-z0-9_]*)$", text, re.IGNORECASE)
        if m:
            return m.group(1)
        if text and not text.endswith(":"):
            break
    return None


def scan_definitions():
    found = set()
    for dirpath, _dirnames, filenames in os.walk(OUT):
        for name in filenames:
            if not name.endswith(".c") or name in SCAN_SKIP:
                continue
            path = os.path.join(dirpath, name)
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                found.update(DEFINITION.findall(fh.read()))
    return found


def main():
    procs = json.load(open(os.path.join(ANALYSIS, "procedures.json")))
    by_bank = {6: read_lines(os.path.join(SRC, "bank6.asm")),
               7: read_lines(os.path.join(SRC, "bank7.asm"))}

    thunks = []
    for proc in procs:
        if proc["thunk"]:
            target = thunk_target(by_bank[proc["bank"]], proc)
            if target:
                thunks.append((proc["name"], proc["addr"], target, proc["bank"]))
            else:
                print("warning: thunk without a JMP target: %s" % proc["name"])

    out = ["/* thunks.c - the original's three-byte `JMP <target>` shims.",
           " *",
           " * GENERATED by c_src/tools/gen_support.py - do not edit.",
           " * Each entry is a bank-API trampoline of the original build ($C000",
           " * j_reset: JMP reset, and so on); in C a thunk is a tail call.",
           " */",
           '#include "labels.h"',
           ""]
    for name, addr, target, bank in thunks:
        out.append("/* $%04X (bank %d) */" % (addr, bank))
        out.append("void %s(void) { %s(); }" % (name, target))
    with open(os.path.join(OUT, "thunks.c"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")

    defined = scan_definitions()
    thunk_names = {t[0] for t in thunks}
    missing = [p for p in procs
               if p["name"] not in defined and p["name"] not in thunk_names]

    # ------------------------------------------------------------- dispatch
    # zanac_call_at(addr) maps an original 6502 entry point to its ported C
    # procedure.  It is what makes the computed control flow of the original
    # (the enemy dispatcher's RTS-jump, switch_case, the PLA/RTS unwinds)
    # work in C.
    entries = sorted({(p["addr"], p["name"]) for p in procs})
    out = ["/* zanac_dispatch.c - call a ported procedure by its 6502 address.",
           " *",
           " * GENERATED by c_src/tools/gen_support.py - do not edit.",
           " * The original computes control flow in a few places (the enemy",
           " * dispatcher jumps through a pair of byte tables with an RTS,",
           " * switch_case indexes an inline word table, some helpers unwind the",
           " * 6502 stack with PLA/RTS).  In C those become zanac_call_at(addr).",
           " */",
           '#include <stdio.h>',
           '#include <stdlib.h>',
           '#include "zanac.h"',
           "",
           "typedef struct { uint16_t addr; void (*fn)(void); } ZanacEntry;",
           "",
           "static const ZanacEntry zanac_dispatch_table[] = {"]
    for addr, name in entries:
        out.append("    { 0x%04X, %s }," % (addr, name))
    out.append("};")
    out.append("")
    out.append("#define ZANAC_DISPATCH_COUNT "
               "(sizeof(zanac_dispatch_table) / sizeof(zanac_dispatch_table[0]))")
    out.append("")
    out.append("void zanac_call_at_missing(uint16_t addr)")
    out.append("{")
    out.append("    long pumps = 0, dispatches = 0, frames = 0;")
    out.append("    neslib_debug_counts(&pumps, &dispatches, &frames);")
    out.append('    fprintf(stderr, "zanac: no ported procedure at $%04X (bank=%d 1E/1F=%02X%02X) "')
    out.append('            "(A=%02X X=%02X Y=%02X slot=%02X type=%02X flags=%02X frame=%ld)\\n",')
    out.append("            (unsigned)addr, (int)zanac_bank(), (unsigned)MEM8(0x1F), (unsigned)MEM8(0x1E),")
    out.append("            (unsigned)A, (unsigned)X, (unsigned)Y,")
    out.append("            (unsigned)MEM8(0x6A), (unsigned)MEM8(0x40),")
    out.append("            (unsigned)MEM8(0x2B), frames);")
    out.append("}")
    out.append("")
    out.append("void zanac_call_at(uint16_t addr)")
    out.append("{")
    out.append("    size_t lo = 0, hi = ZANAC_DISPATCH_COUNT;")
    out.append("    while (lo < hi) {")
    out.append("        size_t mid = lo + (hi - lo) / 2;")
    out.append("        if (zanac_dispatch_table[mid].addr == addr) {")
    out.append("            zanac_dispatch_table[mid].fn();")
    out.append("            return;")
    out.append("        }")
    out.append("        if (zanac_dispatch_table[mid].addr < addr) lo = mid + 1;")
    out.append("        else hi = mid;")
    out.append("    }")
    out.append("    zanac_call_at_missing(addr);")
    out.append("}")
    with open(os.path.join(OUT, "zanac_dispatch.c"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")

    total = len(procs)

    # ---------------------------------------------------------------- stubs
    out = ["/* stubs.c - placeholders for the procedures that are not ported yet.",
           " *",
           " * GENERATED by c_src/tools/gen_support.py - do not edit.",
           " * Regenerated on every build from the list of `void <name>(void)`",
           " * definitions found in c_src/zanac; a procedure disappears from this",
           " * file as soon as its ported definition exists.  Every stub call is",
           " * counted so that a test run reports exactly what is still missing.",
           " */",
           '#include "labels.h"',
           '#include "zanac_stubs.h"',
           ""]
    for proc in missing:
        out.append('void %s(void) { zanac_stub_hit("%s", 0x%04X); }'
                   % (proc["name"], proc["name"], proc["addr"]))
    with open(os.path.join(OUT, "stubs.c"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")

    total = len(procs)
    ported = total - len(thunk_names) - len(missing)
    print("thunks: %d, ported: %d, stubs: %d, total procedures: %d"
          % (len(thunks), ported, len(missing), total))


if __name__ == "__main__":
    main()
